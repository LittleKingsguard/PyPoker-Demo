"""Emit a self-contained HTML fragment: two grids (dead-trunk / live-trunk) of the reference hands."""
import json, html
d=json.load(open('.probe/grids.json')); eq=dict(d['ref']); R=d['results']
HOLES={"quad aces":"A♠ A♦","nut flush":"A♠ Q♠","ace-high straight":"A♠ K♦","trip aces":"A♠ A♦",
       "pair of kings (dry)":"K♥ K♦","2-3 offsuit junk":"2♣ 3♦","2-7 offsuit junk":"2♦ 7♣",
       "2-3 offsuit, all-high board":"2♣ 3♦"}
ORDER=["quad aces","nut flush","ace-high straight","trip aces","pair of kings (dry)",
       "2-3 offsuit junk","2-7 offsuit junk","2-3 offsuit, all-high board"]
LET={'f':'fold','c':'call','r':'raise'}
def cell(seq):
    if seq in (None,'','–'): return '<span class="pp-dash">–</span>'
    if seq=='ERR': return '<span class="pp-dash">err</span>'
    out=[]
    for ch in seq:
        cls={'f':'pp-f','c':'pp-c','r':'pp-r'}.get(ch,'pp-dash')
        out.append(f'<span class="{cls}" title="{LET.get(ch,"no decision")}">{ch}</span>')
    return ''.join(out)
def grid(models, title, note):
    head=''.join(f'<th scope="col">{html.escape(m)}</th>' for m in models)
    rows=[]
    for h in ORDER:
        e=eq[h]
        eqtxt=('0.0%' if e==0 else (f'{e:.2f}%' if e<1 else f'{e:.0f}%'))
        cls='pp-hi' if e>=85 else ('pp-mid' if e>=40 else 'pp-lo')
        cells=''.join(f'<td>{cell(models[m].get(h))}</td>' for m in models)
        rows.append(f'<tr><th scope="row"><span class="pp-hand">{html.escape(h)}</span>'
                    f'<span class="pp-cards">{HOLES[h]}</span></th>'
                    f'<td class="pp-eq {cls}">{eqtxt}</td>{cells}</tr>')
    return f'''
<section class="pp-grid" aria-label="{html.escape(title)}">
  <h3>{html.escape(title)}</h3>
  <p class="pp-note">{note}</p>
  <table>
    <caption class="pp-sr">Reference hands and each model's action, by street: preflop, flop, turn, river.</caption>
    <thead><tr><th scope="col">hand</th><th scope="col">true equity</th>{head}</tr></thead>
    <tbody>{''.join(rows)}</tbody>
  </table>
</section>'''
